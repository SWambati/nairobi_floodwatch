# Public Resident monitoring and verified-account CSV exports.
import csv
import io
import logging
from fastapi import (APIRouter, Depends, HTTPException, Query)
from fastapi.encoders import jsonable_encoder
from fastapi.responses import Response

from src.dashboard.queries import get_locations
from src.dashboard.resident_queries import get_resident_history
from src.auth.authorization import require_verified_resident

router = APIRouter(prefix="/api/resident", tags=["Resident Monitoring"])
logger = logging.getLogger("floodwatch.resident")

# SHARED HISTORY RETRIEVAL
def _load_location_history(location_id, days):
    #Retrieve recorded monitoring history.
    #This data is public and may be used by the Resident Dashboard's risk and rainfall charts.
    #No missing observations are estimated.

    if not get_locations(location_id):
        raise HTTPException(status_code=404, detail="Monitoring point not found.")

    return jsonable_encoder(get_resident_history(location_id, days))

# PUBLIC MONITORING HISTORY
@router.get("/locations/{location_id}/history")
def location_history(location_id: int, days: int = Query(30, ge=1, le=90)):

    #Return publicly available monitoring history.
    #Public monitoring remains accessible even when a Resident has not verified their email address.
    #Browser coordinates are not submitted or stored.

    try:
        return _load_location_history(location_id, days)

    except HTTPException:
        raise

    except Exception as exc:
        logger.exception("Failed to read Resident history for location %s", location_id)
        raise HTTPException(status_code=503, detail=("Monitoring history is temporarily unavailable.")) from exc

# CSV CELL SAFETY
def _safe_csv_cell(value):
    #Serialize values safely for spreadsheet applications.
    #Prevent spreadsheet formula execution in text fields.
    #Numeric values remain numeric.

    if value is None:
        return ""

    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return value

    value = str(value)

    # Protect against spreadsheet formula injection.
    if value.lstrip().startswith(("=", "+", "-", "@")):
        return "'" + value

    return value

# CSV CONSTRUCTION
def _build_history_csv(history):
    #Produce the same five-column export previously, generated by the Resident Dashboard's JavaScript.
    # Prediction and weather observations are combined by Nairobi-local calendar date.
    # Missing values remain blank.

    daily = {}

    predictions = history.get("predictions") or []
    weather_readings = history.get("weather_readings") or []

    # Add recorded flood-risk assessments.
    for prediction in predictions:
        date = prediction.get("local_date")

        if not date:
            continue

        daily[str(date)] = {
            "score": prediction.get("risk_score"),
            "risk": prediction.get("risk_level"),
        }

    # Combine recorded weather snapshots.
    for weather in weather_readings:
        date = weather.get("local_date")

        if not date:
            continue

        date = str(date)

        entry = daily.setdefault(date, {})

        entry["rain"] = weather.get("rainfall")
        entry["temp"] = weather.get("temperature")

    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\r\n")

    writer.writerow([
        "date",
        "model_score",
        "risk_level",
        "precipitation_snapshot_mm",
        "temperature_snapshot_c",
    ])

    for date in sorted(daily):
        record = daily[date]

        writer.writerow([
            _safe_csv_cell(date),
            _safe_csv_cell(record.get("score")),
            _safe_csv_cell(record.get("risk")),
            _safe_csv_cell(record.get("rain")),
            _safe_csv_cell(record.get("temp")),
        ])

    return output.getvalue().encode("utf-8-sig")

# VERIFIED RESIDENT CSV DOWNLOAD
@router.get("/locations/{location_id}/history.csv")
def download_location_history_csv(location_id: int, days: int = Query(30, ge=1, le=90), user=Depends(require_verified_resident)):
    #Export official FloodWatch monitoring history.
    #SECURITY:
    #- Requires an authenticated Resident session.
    #- Requires email_verified = TRUE.
    #- Authorization is enforced in PostgreSQL-backed dependencies before this endpoint runs.
    #- The browser cannot grant itself permission.
    #-The endpoint does not accept a user ID.
    #Public history JSON remains available separately.
    try:
        history = _load_location_history(location_id, days)

        if not isinstance(history, dict):
            raise ValueError("Unexpected Resident history response.")

        predictions = history.get("predictions") or []
        weather = history.get("weather_readings") or []

        if not predictions and not weather:
            raise HTTPException(status_code=404, detail=("No recorded history is available for this monitoring point."))

        content = _build_history_csv(history)

        filename = (f"floodwatch_location_{location_id}_history.csv")

        return Response(
            content=content,
            media_type="text/csv",
            headers={
                "Content-Disposition": (f'attachment; filename="{filename}"'),
                "Cache-Control": "no-store",
                "X-Content-Type-Options": "nosniff",
            },
        )
    
    except HTTPException:
        raise

    except Exception as exc:
        logger.exception("Failed to export Resident history for location %s", location_id)
        raise HTTPException(status_code=503, detail=("Monitoring history export is temporarily unavailable.")) from exc
